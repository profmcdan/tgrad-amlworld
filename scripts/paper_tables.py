"""Rebuild every table and figure of the paper from the saved results (no training, under a minute).

    python scripts/paper_tables.py

Reads results/<NAME>/*.json and writes results/paper_tables.md and figures/paper_{pipeline,coverage,headline}.png.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import paper_figs as Fg  # noqa: E402

R = os.path.join(HERE, "..", "results")
FIG = os.path.join(HERE, "..", "figures")
DS = ["HI-Small", "LI-Small", "HI-Medium", "LI-Medium"]
SMALL, MED = DS[:2], DS[2:]
MET = ["ROC-AUC", "PR-AUC", "F1", "R@1%FPR", "CYCLE R@1%FPR"]
TG = "Graph Transformer + ranked block + temporal cycles"
GTM = "Graph Transformer + matched block"


def J(*p):
    return json.load(open(os.path.join(R, *p)))


SUMMARY = {d: J(d, "summary.json") for d in SMALL}
COMB = {d: J(d, "combine_summary.json") for d in SMALL}
CONF = {d: J(d, "confirm_summary.json") for d in MED}
CMON = {d: J(d, "confirm_monitors.json") for d in MED}
IMPS = {d: J(d, "improve_summary.json") for d in SMALL}
KS = {d: J(d, "ablation_seed0.json")["_shift_ks"] for d in SMALL}
COV = {d: J(d, "coverage_by_L.json") for d in DS}


def comb(d, m):
    a = COMB[d]["agg"][m]
    return {k: (a[k]["mean"], a[k]["std"]) for k in MET + ["val ROC-AUC"]}


def conf(d, m):
    t = CONF[d]["test"][m]
    return {k: (t[k][0], t[k][1]) for k in MET}


def small(d, m):
    t = SUMMARY[d]["results"][m]["test"]
    key = {"ROC-AUC": "ROC-AUC", "PR-AUC": "PR-AUC", "F1": "F1", "R@1%FPR": "Recall@1%FPR",
           "CYCLE R@1%FPR": "CYCLE:Recall@1%FPR"}
    return {k: (t[key[k]]["mean"], t[key[k]]["std"]) for k in MET}


def f(x, m, sd=True):
    d = 4 if m == "PR-AUC" else 3
    return f"{x[0]:.{d}f} ± {x[1]:.{d}f}" if sd else f"{x[0]:.{d}f}"


def md(title, header, rows):
    out = [f"\n## {title}\n", "| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out


L = ["# Tables of the paper (generated by scripts/paper_tables.py from results/<NAME>/)",
     "\nTest window unless marked; learned models: mean ± population std over seeds 0, 1, 2."]

rows = []
for d in DS:
    c = COV[d]
    n, ni, nc = c["n"]["illicit"] + c["n"]["licit"], c["n"]["illicit"], c["n"]["CYCLE"]
    rows.append([d, f"{n:,}", f"{ni:,}", f"{100 * ni / n:.2f}", f"{nc:,}", f"{100 * c['n_unattributed_illicit'] / ni:.0f}",
                 "development" if d in SMALL else "confirmation"])
L += md("Table 1. Test windows of the four AMLworld sets",
        ["Set", "Accounts", "Illicit", "Illicit (%)", "CYCLE", "Illicit in no listed typology (%)", "Role"], rows)

rows = []
names = [("Closed-walk monitor, binary, L=2..6 (original)", "Closed walks, L ≤ 6"),
         ("Closed-walk monitor, binary, L=2..12 (fixed)", "Closed walks, L ≤ 12"),
         ("Temporal-cycle monitor, W=168h, L<=12 (fixed)", "Temporal cycles, W = 168 h"),
         ("Total degree (reference)", "Total degree (reference)")]
for d in MED:
    for k, lab in names:
        r = CONF[d]["test"][k]
        rows.append([d, lab, f"{r['ROC-AUC'][0]:.3f}", f"{r['PR-AUC'][0]:.4f}", f"{r['R@1%FPR'][0]:.3f}",
                     f"{r['CYCLE R@1%FPR'][0]:.3f}"])
L += md("Table 2. Training-free monitors on the confirmation sets", ["Set", "Score", "ROC-AUC", "PR-AUC", "R@1%", "CYCLE R@1%"], rows)

fams = [("MLP", "MLP (attributes)", "MLP + matched block", "MLP + T-GRAD block"),
        ("GCN", "GCN", "GCN (matched)", "GCN + T-GRAD block"), ("GraphSAGE", "GraphSAGE", "GraphSAGE (matched)", "GraphSAGE + T-GRAD block"),
        ("GAT", "GAT", "GAT (matched)", "GAT + T-GRAD block"), ("GIN", "GIN", "GIN (matched)", "GIN + T-GRAD block"),
        ("Graph Transformer", "Graph Transformer", "Graph Transformer (matched)", "Graph Transformer + T-GRAD block")]
rows = [[fam[0]] + [f(small(d, k)["ROC-AUC"], "ROC-AUC", sd=False) for d in SMALL for k in fam[1:]] for fam in fams]
L += md("Table 3. Development sets: test ROC-AUC with attributes only, the matched block and the raw T-GRAD block",
        ["Model", "HI attr.", "HI matched", "HI T-GRAD", "LI attr.", "LI matched", "LI T-GRAD"], rows)

imp = {d: IMPS[d]["learned"] for d in SMALL}
g = lambda d, k: f"{imp[d][k]['test ROC-AUC']['mean']:.3f}"
mx = lambda d, pre: max(v for c, v in KS[d].items() if c.startswith(pre))
rows = [["attributes only", g("HI-Small", "GraphSAGE + attributes only"), g("LI-Small", "GraphSAGE + attributes only"), "–", "–"],
        ["+ decayed walks", g("HI-Small", "GraphSAGE + decayed walks"), g("LI-Small", "GraphSAGE + decayed walks"),
         f"{mx('HI-Small', 'decayed walk'):.3f}", f"{mx('LI-Small', 'decayed walk'):.3f}"],
        ["+ decayed strengths", g("HI-Small", "GraphSAGE + decayed strength"), g("LI-Small", "GraphSAGE + decayed strength"),
         f"{max(KS['HI-Small']['decayed in-strength'], KS['HI-Small']['decayed out-strength']):.3f}",
         f"{max(KS['LI-Small']['decayed in-strength'], KS['LI-Small']['decayed out-strength']):.3f}"],
        ["+ streaming score", g("HI-Small", "GraphSAGE + streaming score"), g("LI-Small", "GraphSAGE + streaming score"),
         f"{KS['HI-Small']['streaming score']:.3f}", f"{KS['LI-Small']['streaming score']:.3f}"],
        ["+ whole block, raw", g("HI-Small", "GraphSAGE + T-GRAD block"), g("LI-Small", "GraphSAGE + T-GRAD block"), "–", "–"],
        ["+ whole block, rank-scaled", g("HI-Small", "GraphSAGE + T-GRAD block, ranked"), g("LI-Small", "GraphSAGE + T-GRAD block, ranked"), "–", "–"],
        ["+ temporal cycles", g("HI-Small", "GraphSAGE + temporal cycles"), g("LI-Small", "GraphSAGE + temporal cycles"), "–", "–"]]
L += md("Table 4. GraphSAGE test ROC-AUC with one feature group added, and train-to-test KS drift among licit accounts",
        ["Features", "HI AUC", "LI AUC", "HI KS", "LI KS"], rows)

models = [(GTM, "matched block (reference)"), ("Graph Transformer + T-GRAD block, ranked", "ranked T-GRAD block"),
          ("Graph Transformer + temporal cycles", "temporal cycles"), (TG, "ranked block + temporal cycles")]
rows = []
for d in SMALL:
    for k, lab in models:
        c = comb(d, k)
        rows.append([d, lab, f(c["val ROC-AUC"], "", sd=False)] + [f(c[m], m) for m in ["ROC-AUC", "PR-AUC", "F1", "CYCLE R@1%FPR"]])
L += md("Table 5. Development sets: Graph Transformer with each feature set (validation ROC-AUC first)",
        ["Set", "Graph Transformer +", "val AUC", "ROC-AUC", "PR-AUC", "F1", "CYCLE R@1%"], rows)
L.append("\nFusion with the training-free monitor: validation selected weight 0 for every model and seed "
         f"({sorted({w for d in SMALL for a in COMB[d]['agg'].values() for w in a.get('w_selected', [])})}).")

hm = [("GraphSAGE + attributes only", "GraphSAGE, attributes"), ("GraphSAGE + matched block", "GraphSAGE, matched"),
      ("GraphSAGE + T-GRAD block", "T-GRAD + GraphSAGE, raw block"), ("GraphSAGE + T-GRAD block, ranked", "T-GRAD + GraphSAGE, ranked block"),
      ("GraphSAGE + temporal cycles", "GraphSAGE + temporal cycles"), (GTM, "Graph Transformer, matched")]
lm = [("GraphSAGE + attributes only", "GraphSAGE, attributes"), ("GraphSAGE + T-GRAD block, ranked", "T-GRAD + GraphSAGE, ranked block"),
      ("GraphSAGE + temporal cycles", "GraphSAGE + temporal cycles"), (GTM, "Graph Transformer, matched"), (TG, "T-GRAD + Graph Transformer")]
rows = [[d, lab] + [f(conf(d, k)[m], m) for m in MET] for d, ms in (("HI-Medium", hm), ("LI-Medium", lm)) for k, lab in ms]
L += md("Table 6. Confirmation sets, every setting fixed before the run", ["Set", "Model"] + MET, rows)
cl = {**CONF["HI-Medium"]["claims"], **CONF["LI-Medium"]["claims"]}
L.append("\nClaims fixed in advance: " + ", ".join(f"{k} {'holds' if v else 'fails'}" for k, v in sorted(cl.items())) + ".")

os.makedirs(FIG, exist_ok=True)
H = {d: ("", comb(d, TG), comb(d, GTM)) for d in SMALL}
H["HI-Medium"] = ("", conf("HI-Medium", "GraphSAGE + T-GRAD block, ranked"), conf("HI-Medium", GTM))
H["LI-Medium"] = ("", conf("LI-Medium", TG), conf("LI-Medium", GTM))
Fg.fig_pipeline(os.path.join(FIG, "paper_pipeline.png"))
Fg.fig_coverage(os.path.join(FIG, "paper_coverage.png"))
Fg.fig_headline(os.path.join(FIG, "paper_headline.png"), H)
open(os.path.join(R, "paper_tables.md"), "w").write("\n".join(L) + "\n")
print("\n".join(L))
