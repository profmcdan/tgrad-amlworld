"""Tables for improvements 1-3 (every number read from the run JSONs).

    python scripts/ibm_aml_aggregate_improve.py --name HI-Small

Writes results/ibm_aml/<NAME>/improve_tables.md and improve_summary.json.
Pre-declared selection rules:
  monitors   validation ROC-AUC of CYCLE accounts vs licit (ibm_aml_improve_monitors.py)
  learned    per model (MLP, GraphSAGE): the feature set with the best mean validation
             ROC-AUC over seeds, among attributes, matched, T-GRAD block (from
             models_seed*.json) and the ablation variants (ablation_seed*.json).
"""
import argparse
import glob
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ibm_aml_common as C  # noqa: E402


def row(r):
    te = r["test"]; c = te["by_pattern"]["CYCLE"]
    return [r["val"]["by_pattern"]["CYCLE"]["AUC_vs_licit"], r["val"]["ROC-AUC"], te["ROC-AUC"], te["PR-AUC"],
            te["Recall@1%FPR"], c["Recall@1%FPR"], c["AUC_vs_licit"]]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--name", default="HI-Small")
    a = ap.parse_args()
    base = os.path.join(C.ROOT, "results", a.name)
    mon = json.load(open(os.path.join(base, "monitors.json")))
    imp = json.load(open(os.path.join(base, "improved_monitors.json")))
    hdr = ("| Monitor | val CYCLE AUC | val AUC | test AUC | test PR-AUC | test R@1%FPR | test CYCLE R@1%FPR "
           "| test CYCLE AUC |\n|---|---|---|---|---|---|---|---|")
    f3 = lambda xs: " | ".join(f"{x:.4f}" if i == 3 else f"{x:.3f}" for i, x in enumerate(xs))
    L = [f"# IBM AML {a.name}: improvements 1-3 (generated by scripts/ibm_aml_aggregate_improve.py)\n",
         "Selection uses the validation window only; thresholds are set on the training snapshot. "
         "Rows marked ★ are the validation-selected configurations; the others are shown for "
         "transparency and were not used for any choice.\n",
         "\n## Training-free monitors\n", hdr]
    L.append(f"| Reference: closed-walk monitor, binary, L=2..6 (original) | {f3(row(mon['models']['Monitor (binary, L=2..6)']))} |")
    L.append(f"| Reference: total degree | {f3(row(mon['models']['Total degree (reference)']))} |")
    for fam in ("closed_walk", "temporal"):
        for nm, r in imp[fam].items():
            star = " ★" if nm == imp[fam + "_selected"] else ""
            L.append(f"| {nm}{star} | {f3(row(r))} |")
    st = imp["temporal_stream_stats"]
    L.append("\nTemporal-cycle stream: " + "; ".join(
        f"{k}: {v['stream_sec']:.0f} s, truncated searches {v['share_truncated']:.2e}" for k, v in st.items()))
    L.append("\n### Share of accounts on a time-respecting cycle (selected configuration)\n")
    L.append("| Split | illicit | licit | CYCLE | non-cycle patterns | unattributed |\n|---|---|---|---|---|---|")
    for sp, cv in imp["temporal_selected_coverage"].items():
        g = lambda k: "–" if cv[k]["share_on_temporal_cycle"] is None else f"{cv[k]['share_on_temporal_cycle']:.3f}"
        L.append(f"| {sp} | {g('illicit')} | {g('licit')} | {g('CYCLE')} | {g('illicit_non_cycle_pattern')} "
                 f"| {g('illicit_unattributed')} |")

    # learned models
    runs = {}
    for f in sorted(glob.glob(os.path.join(base, "models_seed*.json"))) + sorted(glob.glob(os.path.join(base, "ablation_seed*.json"))):
        for m, r in json.load(open(f)).items():
            if m.startswith("_") or not (m.startswith("MLP") or m.startswith("GraphSAGE")):
                continue
            runs.setdefault(m, []).append(r)
    ren = {"MLP (attributes)": "MLP + attributes only", "GraphSAGE": "GraphSAGE + attributes only",
           "GraphSAGE (matched)": "GraphSAGE + matched block"}
    keys = ["val ROC-AUC", "test ROC-AUC", "test PR-AUC", "test R@1%FPR", "test CYCLE R@1%FPR", "test CYCLE AUC"]
    agg = {}
    for m, rs in runs.items():
        vals = np.array([[r["val"]["ROC-AUC"], r["test"]["ROC-AUC"], r["test"]["PR-AUC"], r["test"]["Recall@1%FPR"],
                          r["test"]["by_pattern"]["CYCLE"]["Recall@1%FPR"], r["test"]["by_pattern"]["CYCLE"]["AUC_vs_licit"]]
                         for r in rs])
        agg[ren.get(m, m)] = {"n_seeds": len(rs), **{k: {"mean": float(vals[:, i].mean()), "std": float(vals[:, i].std())}
                                                     for i, k in enumerate(keys)}}
    selected = {}
    for fam in ("MLP", "GraphSAGE"):
        cands = {m: v for m, v in agg.items() if m.startswith(fam)}
        selected[fam] = max(cands, key=lambda m: cands[m]["val ROC-AUC"]["mean"])
        L.append(f"\n## {fam}: feature-set variants (mean ± std over seeds)\n")
        L.append("| Features | seeds | " + " | ".join(keys) + " |\n|---|---|" + "---|" * len(keys))
        for m in sorted(cands, key=lambda m: -cands[m]["val ROC-AUC"]["mean"]):
            v = cands[m]; star = " ★" if m == selected[fam] else ""
            L.append(f"| {m}{star} | {v['n_seeds']} | " + " | ".join(
                f"{v[k]['mean']:.{4 if 'PR' in k else 3}f} ± {v[k]['std']:.{4 if 'PR' in k else 3}f}" for k in keys) + " |")

    abl = sorted(glob.glob(os.path.join(base, "ablation_seed0.json")))
    if abl:
        ks = json.load(open(abl[0])).get("_shift_ks")
        if ks:
            L.append("\n## Train-vs-test shift among licit accounts (KS statistic, seed-independent)\n")
            L.append("| Feature | KS |\n|---|---|")
            for c, v in sorted(ks.items(), key=lambda kv: -kv[1]):
                L.append(f"| {c} | {v:.3f} |")
    json.dump({"dataset": a.name, "monitor_selected": {k: imp[k + "_selected"] for k in ("closed_walk", "temporal")},
               "learned_selected": selected, "learned": agg}, open(os.path.join(base, "improve_summary.json"), "w"), indent=1)
    open(os.path.join(base, "improve_tables.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
