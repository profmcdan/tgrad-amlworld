"""Aggregate IBM AML results over seeds into results/ibm_aml/<NAME>/summary.json and
results/ibm_aml/<NAME>/tables.md (every number read from the run JSONs).

    python scripts/ibm_aml_aggregate.py --name HI-Small
"""
import argparse
import glob
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ibm_aml_common as C  # noqa: E402

METRICS = ["ROC-AUC", "PR-AUC", "F1", "Recall@1%FPR", "FPR@1%thr (realised)"]
GROUPS = C.PATTERNS + ["UNATTRIBUTED"]


def collect(runs):
    """runs: list of {model: {split: eval}} -> {model: {split: {metric: [values]}}}"""
    agg = {}
    for r in runs:
        for m, v in r.items():
            if m.startswith("_"):
                continue
            for sp, e in v.items():
                if sp not in ("train", "val", "test"):
                    continue
                d = agg.setdefault(m, {}).setdefault(sp, {})
                for k in METRICS:
                    d.setdefault(k, []).append(e[k])
                for g in GROUPS:
                    bp = e["by_pattern"][g]
                    if bp.get("n", 0) == 0:
                        continue
                    for k in ("Recall@1%FPR", "Recall@F1thr", "AUC_vs_licit"):
                        d.setdefault(f"{g}:{k}", []).append(bp[k])
                    d[f"{g}:n"] = [bp["n"]]
    out = {}
    for m, v in agg.items():
        out[m] = {sp: {k: {"mean": float(np.mean(x)), "std": float(np.std(x)), "n_seeds": len(x)}
                       for k, x in d.items()} for sp, d in v.items()}
    return out


def fmt(d, k, p=3):
    if k not in d:
        return "–"
    x = d[k]
    return f"{x['mean']:.{p}f}" + (f" ± {x['std']:.{p}f}" if x["n_seeds"] > 1 else "")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--name", default="HI-Small")
    a = ap.parse_args()
    base = os.path.join(C.ROOT, "results", a.name)
    mon = json.load(open(os.path.join(base, "monitors.json")))
    model_runs = [json.load(open(f)) for f in sorted(glob.glob(os.path.join(base, "models_seed*.json")))]
    full_runs = [json.load(open(f)) for f in sorted(glob.glob(os.path.join(base, "tgrad_full_seed*.json")))]
    S = {}
    S.update(collect([mon["models"]]))
    S.update(collect(model_runs))
    S.update(collect(full_runs))
    summary = {"dataset": a.name, "n_seeds_models": len(model_runs), "n_seeds_tgrad_full": len(full_runs),
               "splits": {k: {kk: vv for kk, vv in v.items() if kk != "coverage"} for k, v in mon["splits"].items()},
               "coverage": {k: v["coverage"] for k, v in mon["splits"].items()},
               "tau_selected_h": mon["tau_selected_h"], "tau_train_auc": mon["tau_train_auc"],
               "results": S}
    json.dump(summary, open(os.path.join(base, "summary.json"), "w"), indent=1)

    order = [m for m in mon["models"]] + [m for m in (model_runs[0] if model_runs else {}) if not m.startswith("_")] \
        + [m for m in (full_runs[0] if full_runs else {}) if not m.startswith("_")]
    L = [f"# IBM AML {a.name}: result tables (generated by scripts/ibm_aml_aggregate.py)\n",
         f"Learned models: mean ± std over {len(model_runs)} seeds; full T-GRAD: {len(full_runs)} seeds; "
         "monitors are deterministic. Thresholds (best F1, 1% FPR) set on the training snapshot.\n"]
    for sp in ("test", "val"):
        L.append(f"\n## Overall, {sp} snapshot\n")
        L.append("| Model | ROC-AUC | PR-AUC | F1 | Recall@1%FPR | realised FPR |")
        L.append("|---|---|---|---|---|---|")
        for m in order:
            d = S[m][sp]
            L.append(f"| {m} | " + " | ".join(fmt(d, k, 4 if k == "PR-AUC" else 3) for k in METRICS) + " |")
        L.append(f"\n## Recall at the 1%-FPR training threshold, by pattern type, {sp} snapshot\n")
        L.append("| Model | " + " | ".join(f"{g} (n={int(S[order[0]][sp].get(g + ':n', {'mean': 0})['mean'])})"
                                          for g in GROUPS) + " |")
        L.append("|---|" + "---|" * len(GROUPS))
        for m in order:
            d = S[m][sp]
            L.append(f"| {m} | " + " | ".join(fmt(d, f"{g}:Recall@1%FPR", 2) for g in GROUPS) + " |")
        L.append(f"\n## ROC-AUC of each pattern's accounts against licit accounts, {sp} snapshot\n")
        L.append("| Model | " + " | ".join(GROUPS) + " |")
        L.append("|---|" + "---|" * len(GROUPS))
        for m in order:
            d = S[m][sp]
            L.append(f"| {m} | " + " | ".join(fmt(d, f"{g}:AUC_vs_licit", 3) for g in GROUPS) + " |")
    L.append("\n## Closed-walk coverage (observed binary graph at each snapshot, self-transfers removed)\n")
    L.append("| Split | Group | n | on closed walk L≤6 | L≤12 (diagnostic) | in non-trivial SCC |")
    L.append("|---|---|---|---|---|---|")
    for sp, cv in summary["coverage"].items():
        for g, v in cv.items():
            f = (lambda x: "–" if x is None else f"{x:.3f}")
            L.append(f"| {sp} | {g} | {v['n']} | {f(v['share_closed_walk_L2to6'])} | "
                     f"{f(v['share_closed_walk_L2to12 (diagnostic)'])} | {f(v['share_in_nontrivial_SCC (any cycle length)'])} |")
    open(os.path.join(base, "tables.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
